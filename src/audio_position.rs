pub fn channel_attenuation(
    listener_x: f64,
    listener_y: f64,
    listener_angle: f64,
    source_x: f64,
    source_y: f64,
) -> (u8, u8) {
    let dx = source_x - listener_x;
    let dy = source_y - listener_y;
    // SetSoundLoc uses the camera origin. Rust angles increase toward +Y.
    let (sin, cos) = listener_angle.sin_cos();
    let depth = (dx * cos + dy * sin + crate::world::CAMERA_FORWARD_OFFSET).floor() as i32;
    let lateral = (-dx * sin + dy * cos).floor() as i32;
    let distance = depth.unsigned_abs().min(14) as usize;
    let direction = (lateral.clamp(-15, 14) + 15) as usize;
    (
        LEFT_ATTENUATION[distance][direction],
        RIGHT_ATTENUATION[distance][direction],
    )
}
